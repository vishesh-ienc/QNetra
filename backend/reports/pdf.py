def build_technical_pdf(data: ReportData) -> bytes:
    """
    Generates the Complete Technical Report PDF.
    Comprehensive 14-section technical assessment document.
    """
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=letter,
        leftMargin=36,
        rightMargin=36,
        topMargin=44,
        bottomMargin=44,
    )
    styles = GLOBAL_STYLES
    story = []

    # Title & Identity Banner
    story.extend(
        make_header_block(
            "Complete Cryptographic Assessment",
            "Comprehensive Technical Assessment, Inventory, Risk, Quantum Exposure, CBOM & Evidence",
            data,
            styles,
        )
    )

    # 1. Scope & Assessment Metadata
    story.append(safe_p("1. Assessment Metadata & Scope", styles["SectionHeading"]))
    dur_str = f"{data.duration_seconds:.2f}s" if data.duration_seconds else "N/A"
    story.append(
        safe_p(
            f"<b>Target:</b> {data.target_name} ({data.source_type})<br/>"
            f"<b>Source URL / Path:</b> {data.source_url or data.scan_meta.get('target', {}).get('path', 'Local')}<br/>"
            f"<b>Scan Status:</b> {data.status} (Duration: {dur_str})<br/>"
            f"<b>Analysis Engines:</b> Normalization, CBOM Serializer (CycloneDX 1.6), Quantum Risk, Mosca/HNDL, PQC Recommendations",
            styles["BodyText"],
        )
    )
    story.append(Spacer(1, 6))

    # 2. Executive Posture
    story.append(safe_p("2. Executive Summary & Posture", styles["SectionHeading"]))
    story.append(make_kpi_cards(data, styles))
    story.append(Spacer(1, 10))

    # 3. Cryptographic Posture
    story.append(safe_p("3. Cryptographic Inventory Posture", styles["SectionHeading"]))
    algo_counts: dict[str, int] = {}
    for a in data.assets:
        algo_counts[a["algorithm"]] = algo_counts.get(a["algorithm"], 0) + 1
    algo_summary = ", ".join(f"<b>{k}</b>: {v}" for k, v in sorted(algo_counts.items(), key=lambda x: -x[1])[:10])
    story.append(safe_p(f"Discovered {data.total_assets} normalized assets across top algorithms: {algo_summary}.", styles["BodyText"]))
    story.append(Spacer(1, 8))

    # 4. Normalized Cryptographic Assets Table
    story.append(safe_p("4. Normalized Cryptographic Assets", styles["SectionHeading"]))
    asset_rows = [
        [
            safe_p("Asset ID", styles["TableHead"]),
            safe_p("Algorithm", styles["TableHead"]),
            safe_p("Primitive", styles["TableHead"]),
            safe_p("Risk", styles["TableHead"]),
            safe_p("Threat", styles["TableHead"]),
            safe_p("Urgency", styles["TableHead"]),
            safe_p("Primary File & Line", styles["TableHead"]),
        ]
    ]
    for a in data.assets[:25]:
        sev = a.get("risk_severity") or "LOW"
        sev_color = get_severity_color(sev)
        asset_id = (a.get("asset_id") or "")[:10] + "..."
        algo = a.get("algorithm") or "Unknown"
        prim = (a.get("primitive_type") or "UNKNOWN")[:18]
        threat = a.get("quantum_threat_type") or "NONE"
        urg = a.get("mosca_urgency") or "LOW"
        loc_str = a.get("location_str") or "N/A"
        if len(loc_str) > 36:
            loc_str = "..." + loc_str[-33:]
        asset_rows.append([
            safe_p(asset_id, styles["TableCode"]),
            safe_p(f"<b>{algo}</b>", styles["TableCellBold"]),
            safe_p(prim, styles["TableCell"]),
            safe_p(f"<font color='{sev_color.hexval()}'><b>{sev}</b></font>", styles["TableCell"]),
            safe_p(threat, styles["TableCell"]),
            safe_p(urg, styles["TableCell"]),
            safe_p(loc_str, styles["TableCode"]),
        ])
    if len(data.assets) > 25:
        asset_rows.append([safe_p(f"... [{len(data.assets) - 25} more assets in full inventory]", styles["TableCell"])] + [safe_p("", styles["TableCell"])] * 6)

    t_assets = Table(asset_rows, colWidths=[65, 80, 75, 55, 60, 55, 150])
    t_assets.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), COLOR_BG_ALT),
            ("GRID", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
            ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ])
    )
    story.append(t_assets)
    story.append(Spacer(1, 10))

    # 5. Raw Evidence & Findings Table
    story.append(safe_p("5. Raw Scanner Findings & Evidence", styles["SectionHeading"]))
    find_rows = [
        [
            safe_p("Finding ID", styles["TableHead"]),
            safe_p("Scanner", styles["TableHead"]),
            safe_p("Method", styles["TableHead"]),
            safe_p("Algorithm", styles["TableHead"]),
            safe_p("Confidence", styles["TableHead"]),
            safe_p("Location", styles["TableHead"]),
        ]
    ]
    for f in data.findings[:15]:
        f_id = (f.get("finding_id") or "")[:12] + "..."
        scanner = f.get("scanner_name") or ""
        method = f.get("discovery_method") or ""
        algo = f.get("suspected_algorithm") or ""
        conf = f"{f.get('confidence_score', 0):.2f} ({f.get('confidence_level', '')})"
        loc_str = f.get("location_str") or ""
        if len(loc_str) > 36:
            loc_str = "..." + loc_str[-33:]
        find_rows.append([
            safe_p(f_id, styles["TableCode"]),
            safe_p(scanner, styles["TableCell"]),
            safe_p(method, styles["TableCell"]),
            safe_p(f"<b>{algo}</b>", styles["TableCellBold"]),
            safe_p(conf, styles["TableCell"]),
            safe_p(loc_str, styles["TableCode"]),
        ])
    if len(data.findings) > 15:
        find_rows.append([safe_p(f"... [{len(data.findings) - 15} more findings in full log]", styles["TableCell"])] + [safe_p("", styles["TableCell"])] * 5)

    t_findings = Table(find_rows, colWidths=[75, 80, 75, 85, 80, 145])
    t_findings.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), COLOR_BG_ALT),
            ("GRID", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
            ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ])
    )
    story.append(t_findings)
    story.append(Spacer(1, 10))

    # 6 & 7. Classical and Quantum Security Analysis
    story.append(safe_p("6. Classical & Quantum Exposure Analysis", styles["SectionHeading"]))
    story.append(
        safe_p(
            f"<b>Classical Security:</b> <b>{data.classically_broken_count}</b> assets are classified as classically broken/weak.<br/>"
            f"<b>Shor Exposure:</b> <b>{data.shor_vulnerable_count}</b> assets vulnerable to polynomial-time quantum attacks.<br/>"
            f"<b>Grover Exposure:</b> <b>{data.grover_impacted_count}</b> assets impacted by quadratic speedup bit-halving.<br/>"
            f"<b>Quantum Resistant:</b> <b>{data.quantum_resistant_count}</b> assets safe against quantum cryptanalysis.",
            styles["BodyText"],
        )
    )
    story.append(Spacer(1, 6))

    # 8 & 9. Risk & Mosca Analysis
    story.append(safe_p("7. Risk Scoring & Mosca/HNDL Analysis", styles["SectionHeading"]))
    p = data.mosca_parameters
    story.append(
        safe_p(
            f"<b>Risk Engine:</b> Overall risk score of <b>{data.overall_risk_score:.1f}/100 ({data.overall_severity})</b>.<br/>"
            f"<b>Mosca Inequality:</b> Parameters: Shelf-life <i>X = {p.get('data_shelf_life_years_x', 10)}y</i>, "
            f"Migration time <i>Y = {p.get('migration_time_years_y', 3)}y</i>, Threat horizon <i>Z = {p.get('quantum_threat_horizon_years_z', 10)}y</i>.<br/>"
            f"Triggered assets: <b>{data.mosca_triggered_count}</b>. HNDL exposed assets: <b>{data.hndl_exposed_count}</b>.",
            styles["BodyText"],
        )
    )
    story.append(Spacer(1, 8))

    # 10 & 11. Migration Recommendations
    story.append(safe_p("8. PQC Migration Recommendations", styles["SectionHeading"]))
    story.append(make_migration_table(data, styles, limit=12))
    story.append(Spacer(1, 10))

    # 12. CBOM Summary
    story.append(safe_p("9. Cryptographic Bill of Materials (CBOM) Summary", styles["SectionHeading"]))
    story.append(
        safe_p(
            f"The scan generated a CycloneDX 1.6 compliant Cryptographic Bill of Materials containing "
            f"<b>{data.cbom_component_count}</b> cryptographic components, including algorithm properties, "
            f"key sizes, curves, implementation libraries, and evidence pointers.",
            styles["BodyText"],
        )
    )
    story.append(Spacer(1, 6))

    # 13 & 14. Evidence Traceability & Technical Appendix
    story.append(safe_p("10. Evidence Traceability & Technical Standards", styles["SectionHeading"]))
    story.append(
        safe_p(
            "Every CryptoAsset in QNetra maintains bi-directional audit links to its originating RawFinding records. "
            "Standards applied: NIST SP 800-57 Part 1 Rev 5 (Key Management), NIST FIPS 203 (ML-KEM), "
            "NIST FIPS 204 (ML-DSA), NIST FIPS 205 (SLH-DSA), and CycloneDX 1.6 CBOM specification.",
            styles["BodyText"],
        )
    )

    doc.build(story, canvasmaker=NumberedCanvas)
    return buf.getvalue()



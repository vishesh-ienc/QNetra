def safe_p(text: Any, style: ParagraphStyle) -> Paragraph:
    """Helper that converts text to string and never passes None to Paragraph."""
    if text is None:
        return Paragraph("", style)
    return Paragraph(str(text), style)


def get_severity_color(sev: str) -> colors.Color:
    s = (sev or "").upper()
    if s == "CRITICAL":
        return COLOR_CRITICAL
    if s == "HIGH":
        return COLOR_HIGH
    if s == "MEDIUM":
        return COLOR_MEDIUM
    return COLOR_LOW


def make_header_block(title: str, subtitle: str, data: ReportData, styles: dict) -> list:
    """Creates the standardized top cover/identity banner."""
    story = [
        safe_p(title, styles["DocTitle"]),
        safe_p(subtitle, styles["DocSubtitle"]),
    ]

    # Meta Table: Target, Completed Date, Scan ID, Status
    sev_color = get_severity_color(data.overall_severity)
    meta_data = [
        [
            safe_p("<b>Target:</b>", styles["TableCellBold"]),
            safe_p(data.target_name, styles["TableCell"]),
            safe_p("<b>Scan Date:</b>", styles["TableCellBold"]),
            safe_p(data.completed_at_str, styles["TableCell"]),
        ],
        [
            safe_p("<b>Scan ID:</b>", styles["TableCellBold"]),
            safe_p(data.scan_id[:18] + "...", styles["TableCode"]),
            safe_p("<b>Overall Posture:</b>", styles["TableCellBold"]),
            safe_p(
                f"<font color='{sev_color.hexval()}'><b>{data.overall_severity} ({data.overall_risk_score:.1f}/100)</b></font>",
                styles["TableCell"],
            ),
        ],
    ]
    t = Table(meta_data, colWidths=[65, 205, 95, 175])
    t.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), COLOR_BG_LIGHT),
            ("BOX", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ])
    )
    story.append(t)
    story.append(Spacer(1, 10))
    return story


def make_kpi_cards(data: ReportData, styles: dict) -> Table:
    """Builds the 6-metric summary KPI grid."""
    row_vals = [
        safe_p(f"{data.overall_risk_score:.1f}", styles["KpiValue"]),
        safe_p(str(data.total_assets), styles["KpiValue"]),
        safe_p(str(data.shor_vulnerable_count), styles["KpiValue"]),
        safe_p(str(data.grover_impacted_count), styles["KpiValue"]),
        safe_p(str(data.direct_pqc_count + data.classical_upgrade_count), styles["KpiValue"]),
        safe_p(str(data.quantum_resistant_count), styles["KpiValue"]),
    ]
    row_labels = [
        safe_p("Risk Score", styles["KpiLabel"]),
        safe_p("Total Assets", styles["KpiLabel"]),
        safe_p("Shor Vulnerable", styles["KpiLabel"]),
        safe_p("Grover Impacted", styles["KpiLabel"]),
        safe_p("Migration Required", styles["KpiLabel"]),
        safe_p("Quantum Resistant", styles["KpiLabel"]),
    ]
    card_data = [row_vals, row_labels]
    w = PAGE_WIDTH / 6.0
    t = Table(card_data, colWidths=[w] * 6)
    t.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), COLOR_BG_LIGHT),
            ("BOX", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
            ("TOPPADDING", (0, 0), (-1, 0), 6),
            ("BOTTOMPADDING", (0, 0), (-1, 0), 2),
            ("TOPPADDING", (0, 1), (-1, 1), 2),
            ("BOTTOMPADDING", (0, 1), (-1, 1), 6),
            ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ])
    )
    return t


def make_exposures_table(data: ReportData, styles: dict, limit: int = 8) -> Table:
    """Table of top high-risk assets."""
    rows = [
        [
            safe_p("Algorithm", styles["TableHead"]),
            safe_p("Primitive", styles["TableHead"]),
            safe_p("Risk", styles["TableHead"]),
            safe_p("Threat", styles["TableHead"]),
            safe_p("Urgency", styles["TableHead"]),
            safe_p("Target Replacement", styles["TableHead"]),
            safe_p("Location", styles["TableHead"]),
        ]
    ]
    count = 0
    for a in data.assets:
        sev = a.get("risk_severity") or "LOW"
        if sev not in ("CRITICAL", "HIGH") and count >= limit:
            continue
        count += 1
        sev_color = get_severity_color(sev)
        algo = a.get("algorithm") or "Unknown"
        prim = (a.get("primitive_type") or "UNKNOWN")[:18]
        threat = a.get("quantum_threat_type") or "NONE"
        urg = a.get("mosca_urgency") or "LOW"
        rec_algo = a.get("recommended_algorithm") or "N/A"
        loc_str = a.get("location_str") or "N/A"
        if len(loc_str) > 35:
            loc_str = "..." + loc_str[-32:]

        rows.append([
            safe_p(f"<b>{algo}</b>", styles["TableCellBold"]),
            safe_p(prim, styles["TableCell"]),
            safe_p(f"<font color='{sev_color.hexval()}'><b>{sev} ({a.get('risk_score', 0)})</b></font>", styles["TableCell"]),
            safe_p(threat, styles["TableCell"]),
            safe_p(urg, styles["TableCell"]),
            safe_p(rec_algo, styles["TableCellBold"]),
            safe_p(loc_str, styles["TableCode"]),
        ])
        if count >= limit:
            break

    if len(rows) == 1:
        rows.append([safe_p("No critical or high-risk cryptographic exposures discovered.", styles["TableCell"])] + [safe_p("", styles["TableCell"])] * 6)

    col_widths = [80, 75, 70, 60, 55, 90, 110]
    t = Table(rows, colWidths=col_widths)
    t.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), COLOR_BG_ALT),
            ("GRID", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
            ("RIGHTPADDING", (0, 0), (-1, -1), 4),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ])
    )
    return t


def make_migration_table(data: ReportData, styles: dict, limit: int = 15) -> Table:
    """Table of prioritized migration actions."""
    rows = [
        [
            safe_p("Current Algorithm", styles["TableHead"]),
            safe_p("Category", styles["TableHead"]),
            safe_p("Replacement", styles["TableHead"]),
            safe_p("PQC Standard", styles["TableHead"]),
            safe_p("Urgency", styles["TableHead"]),
            safe_p("Complexity", styles["TableHead"]),
            safe_p("Source Location", styles["TableHead"]),
        ]
    ]

    actions = data.migration_actions[:limit]
    for m in actions:
        urg = m.get("urgency") or "LOW"
        urg_color = get_severity_color(urg)
        cur_algo = m.get("current_algorithm") or "Unknown"
        cat = (m.get("migration_category") or "").replace("_", " ")
        rec_algo = m.get("recommended_algorithm") or "N/A"
        pqc_std = m.get("pqc_standard") or "N/A"
        comp = m.get("migration_complexity") or "MEDIUM"
        loc_str = m.get("location_str") or "N/A"
        if len(loc_str) > 35:
            loc_str = "..." + loc_str[-32:]

        rows.append([
            safe_p(f"<b>{cur_algo}</b>", styles["TableCellBold"]),
            safe_p(cat, styles["TableCell"]),
            safe_p(f"<b>{rec_algo}</b>", styles["TableCellBold"]),
            safe_p(pqc_std, styles["TableCell"]),
            safe_p(f"<font color='{urg_color.hexval()}'><b>{urg}</b></font>", styles["TableCell"]),
            safe_p(comp, styles["TableCell"]),
            safe_p(loc_str, styles["TableCode"]),
        ])

    if len(rows) == 1:
        rows.append([safe_p("No migration actions required.", styles["TableCell"])] + [safe_p("", styles["TableCell"])] * 6)

    col_widths = [90, 85, 90, 75, 55, 55, 90]
    t = Table(rows, colWidths=col_widths)
    t.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), COLOR_BG_ALT),
            ("GRID", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
            ("RIGHTPADDING", (0, 0), (-1, -1), 4),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ])
    )
    return t


def build_executive_pdf(data: ReportData) -> bytes:
    """
    Generates the Executive Cryptographic Assessment PDF.
    A concise, leadership-focused document (2-3 pages).
    """
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=letter,
        leftMargin=36,
        rightMargin=36,
        topMargin=44,
        bottomMargin=44,
    )
    styles = GLOBAL_STYLES
    story = []

    # Title & Identity Banner
    story.extend(
        make_header_block(
            "Executive Cryptographic Assessment",
            "Concise Security Posture, Quantum Threat Exposure & Prioritized Remediation Roadmap",
            data,
            styles,
        )
    )

    # 1. Executive Summary & KPIs
    story.append(safe_p("1. Executive Summary", styles["SectionHeading"]))
    story.append(
        safe_p(
            f"QNetra conducted a static cryptographic discovery and post-quantum vulnerability assessment on "
            f"<b>{data.target_name}</b>. The assessment discovered a total of <b>{data.total_assets}</b> cryptographic assets. "
            f"The overall cryptographic risk posture is assessed as <b>{data.overall_severity}</b> "
            f"with a composite risk index of <b>{data.overall_risk_score:.1f}/100</b>. "
            f"A total of <b>{data.shor_vulnerable_count}</b> assets rely on asymmetric primitives vulnerable to Shor's algorithm, "
            f"and <b>{data.direct_pqc_count + data.classical_upgrade_count}</b> assets require scheduled migration.",
            styles["BodyText"],
        )
    )
    story.append(make_kpi_cards(data, styles))
    story.append(Spacer(1, 10))

    # 2. Key Exposures
    story.append(safe_p("2. Critical & High Cryptographic Exposures", styles["SectionHeading"]))
    story.append(
        safe_p(
            "The following assets represent the highest immediate risk due to vulnerable algorithms, "
            "exposure to quantum cryptanalysis (Shor/Grover), or impending Harvest-Now-Decrypt-Later (HNDL) deadlines:",
            styles["BodyText"],
        )
    )
    story.append(make_exposures_table(data, styles, limit=6))
    story.append(Spacer(1, 10))

    # 3. Quantum Exposure Breakdown (Shor & Grover)
    story.append(safe_p("3. Quantum Exposure & Vulnerability Breakdown", styles["SectionHeading"]))
    vuln_algos = sorted({a["algorithm"] for a in data.assets if a.get("quantum_vulnerable")})
